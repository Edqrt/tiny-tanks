import { parseMapPack,serializeMaps } from './tilemap.js';

export function formatLevelSource(levels) {
  const valid=parseMapPack({version:2,levels});
  return `// Generated by the level editor.\nexport const TILE_LEVELS = ${JSON.stringify(valid,null,2)};\n`;
}

export function createLevelSaver({fetcher=globalThis.fetch,pickFile,download,apiBase=new URL('./api/',import.meta.url)}={}) {
  let serverAvailable=false,fileHandle=null;
  return {
    async detect() {
      try {
        const response=await fetcher(new URL('editor-capabilities',apiBase),{signal:AbortSignal.timeout(3000),cache:'no-store'});
        const info=response.ok?await response.json():null;
        serverAvailable=info?.service==='tiny-tanks'&&info.saveLevels===true;
      }catch{serverAvailable=false;}
      return serverAvailable?'server':pickFile?'file':'download';
    },
    async save(levels) {
      // File pickers must run in the click handler, before any network await.
      const source=formatLevelSource(levels);
      if(serverAvailable){
        const response=await fetcher(new URL('levels',apiBase),{method:'POST',headers:{'Content-Type':'application/json'},body:serializeMaps(levels)});
        if(!response.ok){const data=await response.json().catch(()=>({}));throw new Error(data.error||'専用サーバーに保存できませんでした。サーバーの状態を確認してください。');}
        return {method:'server'};
      }
      if(!pickFile){download(source,'levels.js');return {method:'download'};}
      const handle=fileHandle||await pickFile({suggestedName:'levels.js',types:[{description:'レベルデータ（JavaScript）',accept:{'text/javascript':['.js']}}]});
      if(handle.name!=='levels.js')throw new Error('Tanksフォルダーの levels.js を保存先に選んでください。');
      let writable;
      try{
        writable=await handle.createWritable();await writable.write(source);await writable.close();fileHandle=handle;
      }catch(error){
        fileHandle=null;
        if(writable)await writable.abort().catch(()=>{});
        throw error;
      }
      return {method:'file'};
    },
  };
}
